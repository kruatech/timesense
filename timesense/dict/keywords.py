    @staticmethod
    def _cardinal_value(word, morph=None):
        if not word:
            return None
        wl = word.lower()
        if wl in Keywords._CARDINAL_WORDS:
            return Keywords._CARDINAL_WORDS[wl]
        if morph and getattr(morph, "available", False):
            n = morph.normalize(wl)
            if n in Keywords._CARDINAL_WORDS:
                return Keywords._CARDINAL_WORDS[n]
        return None

    @staticmethod
    def parse_cardinal(tokens, start, morph=None):
        """Считывает последовательность числительных словами начиная с индекса
        start и собирает составное число (напр. «сорок пять» → 45,
        «сто двадцать» → 120). Возвращает (значение, число_токенов).
        Если на позиции стоит цифра — принимает её как одно значение."""
        if start >= len(tokens):
            return (None, 0)
        # цифра
        if tokens[start].value.isdigit():
            return (int(tokens[start].value), 1)
        current = 0
        consumed = 0
        i = start
        got = False
        while i < len(tokens):
            v = Keywords._cardinal_value(tokens[i].value, morph)
            if v is None:
                break
            if v >= 100:
                current = (current or 1) * v if v == 100 else current + v
            else:
                current += v
            got = True
            consumed += 1
            i += 1
            if v < 20:  # единица/подросток завершают число
                break
        if not got:
            return (None, 0)
        return (current, consumed)

    @staticmethod
    def parse_compound_minutes(tokens, start_index, morph=None):
        if start_index >= len(tokens):
            return (None, 0)
        first_val = tokens[start_index].value.lower()
        fn = first_val
        if morph and morph.available:
            fn = morph.normalize(first_val)
        tv = Keywords._TENS.get(fn) or Keywords._TENS.get(first_val)
        if tv is not None:
            if start_index + 1 < len(tokens):
                sv = tokens[start_index + 1].value.lower()
                sn = sv
                if morph and morph.available:
                    sn = morph.normalize(sv)
                uv = Keywords._UNITS.get(sn) or Keywords._UNITS.get(sv)
                if uv is not None:
                    r = tv + uv
                    if 0 <= r <= 59:
                        return (r, 2)
            if 0 <= tv <= 59:
                return (tv, 1)
        sv = Keywords.parse_number_word(first_val, morph)
        if sv is not None and 0 <= sv <= 59:
            return (sv, 1)
        return (None, 0)

    @staticmethod
    def parse_number_word(word, morph=None, next_word=None):
        if not word:
            return None
        wl = word.lower()
        if next_word:
            c = wl + " " + next_word.lower()
            dm = Keywords._get_direct_map()
            if c in dm:
                return dm[c]
            if c in Keywords._NORMALIZED_TO_NUMBER:
                return Keywords._NORMALIZED_TO_NUMBER[c]
        if morph and morph.available:
            n = morph.normalize(wl)
            if n in Keywords._NORMALIZED_TO_NUMBER:
                return Keywords._NORMALIZED_TO_NUMBER[n]
        if wl in Keywords._NORMALIZED_TO_NUMBER:
            return Keywords._NORMALIZED_TO_NUMBER[wl]
        dm = Keywords._get_direct_map()
        if wl in dm:
            return dm[wl]
        return None

